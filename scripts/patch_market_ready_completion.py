# Build the market-ready seed migration from compact compressed structured data.
content_blob = ''.join((assets / f'content_data_{i}.b64').read_text().strip() for i in range(1, 5))
data = json.loads(zlib.decompress(base64.b64decode(content_blob)).decode('utf-8'))


def q(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def text_array(values):
    return 'ARRAY[' + ','.join(q(x) for x in values) + ']::text[]'

sql = [
    '-- FluentX market-ready content pack generated by CI.',
    '-- Idempotent: existing natural-key rows are preserved.',
    'BEGIN;',
]

for word, definition, example, category in data['v']:
    sql.append(
        f"INSERT INTO public.vocabulary_words (word, definition, example_sentence, category) "
        f"SELECT {q(word)}, {q(definition)}, {q(example)}, {q(category)} "
        f"WHERE NOT EXISTS (SELECT 1 FROM public.vocabulary_words WHERE lower(word)=lower({q(word)}) AND category={q(category)});"
    )

for title, explanation, category, order_index in data['gl']:
    sql.append(
        f"INSERT INTO public.grammar_lessons (title, explanation, category, order_index) "
        f"SELECT {q(title)}, {q(explanation)}, {q(category)}, {order_index} "
        f"WHERE NOT EXISTS (SELECT 1 FROM public.grammar_lessons WHERE title={q(title)});"
    )
for question, options, correct_index, title in data['gq']:
    sql.append(
        f"INSERT INTO public.grammar_questions (lesson_id, question_text, options, correct_index) "
        f"SELECT l.id, {q(question)}, {text_array(options)}, {correct_index} FROM public.grammar_lessons l "
        f"WHERE l.title={q(title)} AND NOT EXISTS (SELECT 1 FROM public.grammar_questions q WHERE q.question_text={q(question)});"
    )

for title, category, transcript in data['lc']:
    sql.append(
        f"INSERT INTO public.listening_clips (title, category, transcript) "
        f"SELECT {q(title)}, {q(category)}, {q(transcript)} "
        f"WHERE NOT EXISTS (SELECT 1 FROM public.listening_clips WHERE title={q(title)});"
    )
for question, options, correct_index, title in data['lq']:
    sql.append(
        f"INSERT INTO public.listening_questions (clip_id, question_text, options, correct_index) "
        f"SELECT c.id, {q(question)}, {text_array(options)}, {correct_index} FROM public.listening_clips c "
        f"WHERE c.title={q(title)} AND NOT EXISTS (SELECT 1 FROM public.listening_questions q WHERE q.question_text={q(question)});"
    )

for title, category, instructions in data['w']:
    sql.append(
        f"INSERT INTO public.writing_prompts (title, category, instructions) "
        f"SELECT {q(title)}, {q(category)}, {q(instructions)} "
        f"WHERE NOT EXISTS (SELECT 1 FROM public.writing_prompts WHERE title={q(title)});"
    )

for title, category, description, system_prompt in data['a']:
    sql.append(
        f"INSERT INTO public.ai_practice_scenarios (title, category, description, system_prompt) "
        f"SELECT {q(title)}, {q(category)}, {q(description)}, {q(system_prompt)} "
        f"WHERE NOT EXISTS (SELECT 1 FROM public.ai_practice_scenarios WHERE title={q(title)});"
    )

sql += ['COMMIT;', '']
write_bytes('supabase/migrations/0013_market_ready_content.sql', '\n'.join(sql).encode('utf-8'))

