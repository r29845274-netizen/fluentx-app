from pathlib import Path
import sys, zlib, base64, json

root = Path(sys.argv[1] if len(sys.argv) > 1 else 'fluentx_admin_secure')
assets = Path(__file__).resolve().parent / 'payloads'


def decode_payload(name: str) -> bytes:
    raw = (assets / name).read_text().strip()
    return zlib.decompress(base64.b64decode(raw))


def write_bytes(rel: str, data: bytes) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    print(f'Applied {rel}')

